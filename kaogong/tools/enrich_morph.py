def decompose(w, wordset):
    """返回 (parts, sum_text) 或 None。parts=[(片段, 类型, 含义), ...]
    严格校验：词干必须命中词根表（→词根）或词表词头（→词干），宁缺毋滥。
    主流程按剥离构造（stem=wl[:-len(suf)] 等），拼接恒成立；仅人工白名单需校验拼接。"""
    wl = w.lower()
    # 人工白名单
    if wl in MANUAL and MANUAL[wl]:
        parts, sumtext = MANUAL[wl]
        # 校验拼接
        if "".join(p[0] for p in parts).lower() == wl:
            return parts, sumtext

    def stem_hit(s):
        """词干命中判定：优先词根表，其次词表词头，再次基础词干表；
        变形回查：i→y（daily→day）、+e（creat→create）、双写（sunn→sun）。
        返回 (类型, 含义, 显示词形) 或 None"""
        def hit_direct(t):
            if t in ROOTS:
                return ("词根", ROOTS[t], t)
            if t in wordset and len(t) >= 3:
                return ("词干", hint_cache.get(t, ""), t)
            if t in STEM_WORDS:
                return ("词干", STEM_WORDS[t], t)
            return None
        h = hit_direct(s)
        if h:
            return h
        # i→y（词干元音变形：dai→day）
        if len(s) >= 3 and s.endswith("i"):
            h = hit_direct(s[:-1] + "y")
            if h:
                return h
        # +e（词干去 e：creat→create）
        if len(s) >= 3:
            h = hit_direct(s + "e")
            if h:
                return h
        # 双写（sunn→sun）
        if len(s) >= 4 and s[-1] == s[-2]:
            h = hit_direct(s[:-1])
            if h:
                return h
        # il→le（abil→able：能力词干变形）
        if len(s) >= 5 and s.endswith("il"):
            h = hit_direct(s[:-2] + "le")
            if h:
                return h
        return None

    # 1) 前缀 + 词干 + 后缀
    for suf, scn in SUFFIXES:
        if not wl.endswith(suf) or len(wl) - len(suf) < 3:
            continue
        stem = wl[:-len(suf)]
        hit = stem_hit(stem)
        if hit:
            return [(hit[2], hit[0], hit[1]), (suf, "后缀", scn)], _sum_text([(hit[2], hit[0], hit[1]), (suf, "后缀", scn)], w)
        for pref, pcn in PREFIXES:
            if not stem.startswith(pref) or len(stem) - len(pref) < 3:
                continue
            root = stem[len(pref):]
            rh = stem_hit(root)
            if rh:
                return [(pref, "前缀", pcn), (rh[2], rh[0], rh[1]), (suf, "后缀", scn)], _sum_text([(pref, "前缀", pcn), (rh[2], rh[0], rh[1]), (suf, "后缀", scn)], w)
    # 2) 前缀 + 词干
    for pref, pcn in PREFIXES:
        if not wl.startswith(pref) or len(wl) - len(pref) < 3:
            continue
        root = wl[len(pref):]
        rh = stem_hit(root)
        if rh:
            return [(pref, "前缀", pcn), (rh[2], rh[0], rh[1])], _sum_text([(pref, "前缀", pcn), (rh[2], rh[0], rh[1])], w)
    # 3) 词干 + 后缀
    for suf, scn in SUFFIXES:
        if not wl.endswith(suf) or len(wl) - len(suf) < 3:
            continue
        stem = wl[:-len(suf)]
        hit = stem_hit(stem)
        if hit:
            return [(hit[2], hit[0], hit[1]), (suf, "后缀", scn)], _sum_text([(hit[2], hit[0], hit[1]), (suf, "后缀", scn)], w)
    return None

hint_cache = {}   # w -> 词表首义项（词干命中词表词时的释义提示）


def _sum_text(parts, w):
    """把词素含义串成联想提示"""
    root_parts = [p for p in parts if p[1] == "词根"]
    affix_parts = [p for p in parts if p[1] != "词根"]
    chunk = " + ".join("%s（%s）" % (p[0], p[2]) for p in parts)
    return chunk

