def load_vocab():
    raw = open(VB_JS, "rb").read()
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError:
        text = raw.decode("gbk", errors="replace")
    m = re.search(r"window\.KG_VOCAB\s*=\s*(\[.*?\])\s*;", text, re.S)
    if not m:
        raise RuntimeError("vocab.js 解析失败")
    return json.loads(m.group(1))

def main():
    batches = load_vocab()
    wordmap = {}   # w -> {w, cn}
    for b in batches:
        for w in b.get("words", []):
            wordmap.setdefault(w.get("w", "").lower(), w)
    global hint_cache
    for k, w in wordmap.items():
        cn = (w.get("cn") or "")
        first = cn.split("；")[0].split(";")[0].strip()
        hint_cache[k] = first[:24]

    # 1) 逐词拆解
    result = {}
    stats = {"total": 0, "ok": 0, "prefix": 0, "suffix": 0, "root": 0, "manual": 0}
    for k, w in wordmap.items():
        if not k:
            continue
        stats["total"] += 1
        dec = decompose(k, set(wordmap.keys()))
        if not dec:
            continue
        parts, sumtext = dec
        stats["ok"] += 1
        kinds = [p[1] for p in parts]
        if "前缀" in kinds:
            stats["prefix"] += 1
        if "后缀" in kinds:
            stats["suffix"] += 1
        if "词根" in kinds:
            stats["root"] += 1
        if k in MANUAL and MANUAL[k]:
            stats["manual"] += 1
        # 核心部分（词根+词干，用于词族聚类）
        cores = [p[0] for p in parts if p[1] in ("词根", "词干")]
        result[k] = {"morph": [{"p": p[0], "k": p[1], "c": p[2]} for p in parts],
                     "sum": sumtext, "cores": cores}
        cn0 = hint_cache.get(k, "")
        result[k]["cn0"] = cn0

    # 2) 词族聚类：core（词根+词干）-> [词]
    core_words = {}
    for k, v in result.items():
        for c in v.get("cores", []):
            core_words.setdefault(c, set()).add(k)

    # 3) 组装 family（同词根/词干其他词，带释义）
    for k, v in result.items():
        fam = []
        seen = set()
        for c in v.get("cores", []):
            for other in sorted(core_words.get(c, [])):
                if other == k or other in seen:
                    continue
                seen.add(other)
                fam.append({"w": other, "cn": hint_cache.get(other, "")})
        v["family"] = fam[:10]
        v.pop("cores", None)
        v.pop("cn0", None)

    # 3b) 拆解失败的词：反查词族（以该词为词干/词根的词），仍可联想记忆
    no_morph = [k for k in wordmap if k not in result]
    for k in no_morph:
        fam = []
        seen = set()
        for c, ws in core_words.items():
            if k in ws:
                for other in sorted(ws):
                    if other == k or other in seen:
                        continue
                    seen.add(other)
                    fam.append({"w": other, "cn": hint_cache.get(other, "")})
        if fam:
            result[k] = {"morph": [], "sum": "", "family": fam[:10]}

    # 4) 输出 morph.js（独立数据源，供审计/复用）
    js = "window.KG_MORPH = " + json.dumps(result, ensure_ascii=False, indent=1) + ";\n"
    with open(OUT_JS, "w", encoding="utf-8", newline="\n") as f:
        f.write(js)
    print("OUT %s (%d bytes)" % (OUT_JS, os.path.getsize(OUT_JS)))

    # 5) 合并进 vocab.js：词素数据跟随词表同一文件加载（script 加载链路已验证最稳；
    #    Actions 每日 build_data.py 重建 vocab.js 后会自动重跑本脚本，保证词素不丢）
    if os.path.exists(VB_JS):
        with open(VB_JS, "r", encoding="utf-8", newline="\n") as f:
            vb = f.read()
        # 幂等：若已含 KG_MORPH 则先剥离旧段再追加，避免重复定义（重复定义会被后段覆盖，不报错但保持干净）
        marker = "window.KG_MORPH = "
        idx = vb.find(marker)
        if idx >= 0:
            vb = vb[:idx].rstrip() + "\n"
        vb = vb.rstrip() + "\n\n" + js
        with open(VB_JS, "w", encoding="utf-8", newline="\n") as f:
            f.write(vb)
        print("OK  词素数据已合并进 vocab.js（%d bytes，幂等）" % os.path.getsize(VB_JS))
    print("    前缀拆解 %d · 后缀拆解 %d · 词根命中 %d · 人工白名单 %d" % (stats["prefix"], stats["suffix"], stats["root"], stats["manual"]))
    print("OK  词素标注 %d/%d 词（%.1f%%）" % (stats["ok"], stats["total"], 100.0 * stats["ok"] / max(1, stats["total"])))

    # 抽样展示
    for sample in ["regardless", "regard", "international", "unhappy", "useful", "respect"]:
        if sample in result:
            print("SAMPLE %s -> %s" % (sample, json.dumps(result[sample], ensure_ascii=False)))

