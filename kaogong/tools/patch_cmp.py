def main():
    sets = sorted(set(k[0] for k in CMP))
    for s in sets:
        fp = os.path.join(BASE, 'idiom-%03d.json' % s)
        d = json.load(io.open(fp, encoding='utf-8'))
        log = []
        for it in d['items']:
            key = (d['set'], it['w'])
            if key not in CMP:
                raise SystemExit('missing cmp for %s' % (key,))
            arr = CMP[key]
            if len(arr) != len(it['options']):
                raise SystemExit('len mismatch %s' % (key,))
            ai = 'ABCD'.index((it['answer'] or ['A'])[0])
            if not arr[ai].get('self'):
                raise SystemExit('self flag misplaced %s' % (key,))
            for k, c in enumerate(arr):
                if c.get('self') and k != ai:
                    raise SystemExit('dup self %s' % (key,))
            it['cmp'] = arr
            log.append(it['w'])
        io.open(fp, 'w', encoding='utf-8').write(json.dumps(d, ensure_ascii=False, indent=1))
        print('OK set %d -> %s' % (s, '、'.join(log)))


main()
