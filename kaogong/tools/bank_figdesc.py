# 少量题解析为空 → 给通用兜底
GENERIC = "题干与选项均为几何图形（图形推理题）。若图片无法加载，可先跳过此题，不影响其他题目作答；建议网络恢复后刷新重试。"


def main():
    obj = json.load(open(PATH, encoding="utf-8"))
    n_fig = n_full = n_gen = 0
    for q in obj.get("questions", []):
        fig = q.get("fig")
        if not fig or not fig.get("imgs"):
            continue
        n_fig += 1
        fid = os.path.basename((fig["imgs"][0] or "")).split("_1")[0]
        if fid in DESCS:
            fig["desc"] = DESCS[fid]
            n_full += 1
            continue
        exp = (q.get("ana") or {}).get("sol") or ""
        # ana.sol 是 figure_pool.exp 转来的规律描述
        if exp and exp != "（解析缺失）":
            fig["desc"] = "题干为图形序列，选项 A~%s 为候选图形（本题需配合图片作答）。规律提示：%s 若图片无法显示，可先跳过本题，不影响其他题目。" % (
                "ABCDEFGH"[len(q.get("options") or []) - 1], exp.strip())
        else:
            fig["desc"] = GENERIC
        n_gen += 1
    json.dump(obj, open(PATH, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("图形题 %d：完整描述 %d · 规律兜底 %d" % (n_fig, n_full, n_gen))


if __name__ == "__main__":
    main()
